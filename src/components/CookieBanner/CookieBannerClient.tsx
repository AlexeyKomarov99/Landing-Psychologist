'use client'

import dynamic from 'next/dynamic'

// Согласие на cookie известно только на клиенте (localStorage). Если рендерить
// баннер на сервере, React обязан на первом клиентском рендере показать
// "серверный" снапшот (null → баннер видим) и лишь потом переключиться на
// реальное значение — отсюда вспышка баннера при обновлении страницы.
// Рендерим компонент только на клиенте, чтобы первый рендер сразу шёл
// с реальным значением из localStorage, без промежуточного состояния.
const CookieBanner = dynamic(() => import('./CookieBanner'), { ssr: false })

export default CookieBanner
